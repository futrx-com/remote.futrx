package project

// Secrets are mirrored to <project.Cwd>/.env so dotenv-aware tools (Python
// python-dotenv, Node dotenv, shell `set -a; source .env`, etc.) running
// inside the container see them too. The container's `claude` process gets
// them via `--env` separately — this file is the convenience copy for any
// scripts the agent runs.
//
// The secrets go in a marked block at the end of the file. Lines outside the
// block belong to the project (a framework's own .env, for example) and are
// kept as they are.
//
// Ownership: the file is chowned to the host uid that maps to root inside
// the unprivileged container's idmap (LXD default = 1000000). Mode 0600.

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// containerRootHostUID is the host uid that LXD's default idmap presents as
// root inside the unprivileged container. Duplicated from the containers
// package — they must stay in lockstep.
const containerRootHostUID = 1000000

const envFileName = ".env"

// legacyEnvHeader starts files written before secrets moved into a block.
// Those files held nothing but secrets, so they are replaced whole.
const legacyEnvHeader = "# Generated by remote.futrx — managed via project Secrets UI.\n"

const (
	envBlockStart = "# >>> remote.futrx project secrets: managed via the Secrets UI, edits in this block are overwritten >>>"
	envBlockEnd   = "# <<< remote.futrx project secrets <<<"
)

func (s *secretStore) syncEnvFile(ctx context.Context, id ID, cwd string) error {
	if cwd == "" || s.repo == nil {
		return nil
	}
	secrets, err := s.repo.List(ctx, id)
	if err != nil {
		return fmt.Errorf("list secrets: %w", err)
	}
	return writeEnvFile(cwd, secrets)
}

func writeEnvFile(cwd string, secrets []Secret) error {
	path := filepath.Join(cwd, envFileName)
	existing, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read .env: %w", err)
	}
	content := mergeEnvFile(string(existing), secrets)
	if content == "" {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove .env: %w", err)
		}
		return nil
	}

	// Atomic write: temp file in the same dir, then rename.
	tmp, err := os.CreateTemp(cwd, ".env-*.tmp")
	if err != nil {
		return fmt.Errorf("create temp .env: %w", err)
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return fmt.Errorf("chmod temp .env: %w", err)
	}
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return fmt.Errorf("write temp .env: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp .env: %w", err)
	}
	// Chown to the container's mapped root uid BEFORE rename so the
	// container sees correct ownership the instant the file appears.
	if err := os.Chown(tmp.Name(), containerRootHostUID, containerRootHostUID); err != nil {
		return fmt.Errorf("chown temp .env: %w", err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return fmt.Errorf("rename .env: %w", err)
	}
	return nil
}

// mergeEnvFile returns existing with its secrets block replaced by one for
// secrets, or removed when there are none. Everything outside the block is
// kept. An empty result means the file should not exist.
func mergeEnvFile(existing string, secrets []Secret) string {
	own := existing
	if strings.HasPrefix(own, legacyEnvHeader) {
		own = ""
	}
	own = strings.TrimRight(stripEnvBlock(own), "\n")

	var b strings.Builder
	if own != "" {
		b.WriteString(own)
		b.WriteByte('\n')
	}
	if len(secrets) == 0 {
		return b.String()
	}
	if own != "" {
		b.WriteByte('\n')
	}
	b.WriteString(envBlockStart)
	b.WriteByte('\n')
	for _, sec := range secrets {
		b.WriteString(sec.Key)
		b.WriteByte('=')
		b.WriteString(escapeEnvValue(sec.Value))
		b.WriteByte('\n')
	}
	b.WriteString(envBlockEnd)
	b.WriteByte('\n')
	return b.String()
}

// stripEnvBlock removes the secrets block and the blank line written before
// it. A start marker with no end marker drops the rest of the file, since
// everything after it was written here.
func stripEnvBlock(content string) string {
	lines := strings.SplitAfter(content, "\n")
	out := make([]string, 0, len(lines))
	inBlock := false
	for _, line := range lines {
		trimmed := strings.TrimRight(line, "\r\n")
		switch {
		case !inBlock && trimmed == envBlockStart:
			inBlock = true
			if n := len(out); n > 0 && strings.TrimRight(out[n-1], "\r\n") == "" {
				out = out[:n-1]
			}
		case inBlock && trimmed == envBlockEnd:
			inBlock = false
		case !inBlock:
			out = append(out, line)
		}
	}
	return strings.Join(out, "")
}

// escapeEnvValue produces a double-quoted .env value with conservative
// escaping: backslash and double-quote get backslash-escaped; \n and \r
// become literal \n / \r escape sequences (most dotenv libs decode them).
func escapeEnvValue(v string) string {
	var b strings.Builder
	b.Grow(len(v) + 2)
	b.WriteByte('"')
	for _, r := range v {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
