package pluginhost

import (
	"fmt"

	"github.com/futrx-com/remote.futrx.com/pkg/appplugin"
)

// pluginModuleFile is the go.mod compiled for an image's plugin. Its module
// path is local and never published; what matters is that the SDK keeps its
// canonical import path through the replace, so the same source compiles in a
// checkout of this repository and in this generated directory.
func (b *Builder) pluginModuleFile() string {
	return fmt.Sprintf(`// Generated by the remote.futrx plugin host. Do not edit.
module futrx.local/appplugin/image

go %s

require (
	%s v0.0.0
	%s %s
)

require (
%s)

replace %s => ../sdk
`,
		b.pins.goVersion,
		appplugin.ModulePath,
		goPluginModule, b.pins.require(goPluginModule, goPluginFallbackVersion),
		b.pins.indirectBlock(appplugin.ModulePath, goPluginModule),
		appplugin.ModulePath,
	)
}

// sdkModuleFile is the go.mod of the materialized SDK. It carries the same
// pins so the two modules agree without a workspace file.
func (b *Builder) sdkModuleFile() string {
	return fmt.Sprintf(`// Generated by the remote.futrx plugin host. Do not edit.
module %s

go %s

require %s %s

require (
%s)
`,
		appplugin.ModulePath,
		b.pins.goVersion,
		goPluginModule, b.pins.require(goPluginModule, goPluginFallbackVersion),
		b.pins.indirectBlock(appplugin.ModulePath, goPluginModule),
	)
}

const (
	goPluginModule = "github.com/hashicorp/go-plugin"
	// goPluginFallbackVersion is used only when build info is unavailable,
	// which in practice means a test binary. TestGoPluginFallbackMatchesGoMod
	// keeps it in step with the server's own requirement.
	goPluginFallbackVersion = "v1.8.0"
)
